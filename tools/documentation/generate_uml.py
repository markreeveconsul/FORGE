used=[]
header=['!pragma layout smetana','skinparam classAttributeIconSize 0','skinparam shadowing false','skinparam backgroundColor white','skinparam defaultFontName SansSerif','skinparam defaultFontSize 12','skinparam classBackgroundColor #F7F8FA','skinparam classBorderColor #455568','skinparam ArrowColor #697A8D','skinparam packageStyle rectangle','skinparam nodesep 25','skinparam ranksep 30','hide empty members']
blocks=[];index=[]
for key,title,names in groups:
 names=names.split();missing=[n for n in names if n not in top]
 if missing:raise RuntimeError(missing)
 types=[top[n] for n in names];used+=names
 lines=['@startuml '+key,*header,'title FORGE '+title,'caption Declared API excerpts. Full signatures and nested types are in CLASS-REFERENCE.md.']
 ui=all(t['package'].endswith('.ui') for t in types)
 # Interface sheets show a concise operation selection; domain fields remain visible.
 for t in types:lines+=declared(t)
 edges=set()
 for t in types:
  for base,style in [(t['extends'],'<|--')]+[(b,'<|..') for b in t['implements']]:
   simple=re.sub('<.*','',base).split('.')[-1]
   if simple in names:edges.add(f'{alias(top[simple])} {style} {alias(t)}')
  for f in t['fields']:
   for other in types:
    if other==t:continue
    if re.search(r'(?<![\w.])'+re.escape(other['name'])+r'(?![\w.])',f['type']):edges.add(f'{alias(t)} --> {alias(other)} : {f["name"]}')
 if key=='01_roles_payments':
  for n in ['CashOnDeliveryPayment','SimulatedWalletPayment']:edges.add(f'{alias(top[n])} ..> {alias(top["PaymentResult"])} : returns')
 if key=='02_products_carts':
  edges.add(f'{alias(top["Cart"])} "1" *-- "0..*" {alias(top["CartItem"])} : owns lines')
  edges={e for e in edges if not (e.startswith(alias(top['Cart'])+' --> '+alias(top['CartItem'])))}
 if key=='03_orders_reviews':
  edges.add(f'{alias(top["Order"])} "1" *-- "1..*" {alias(top["OrderItem"])} : owns snapshots')
  edges={e for e in edges if not e.startswith(alias(top['Order'])+' --> '+alias(top['OrderItem']))}
 if key=='10_application':
  edges.add(f'{alias(top["ShopApp"])} ..> {alias(top["Services"])} : creates')
 if key=='11_customer_screens':
  for t in types:
   if t['name']!='ShopWindow':edges.add(f'{alias(top["ShopWindow"])} ..> {alias(t)} : opens')
 if key=='12_admin_screens':
  for n in ['AdminReportsView','AdminView','OrderProcessingView','AiManagerView']:edges.add(f'{alias(top["AdminWorkspace"])} ..> {alias(top[n])} : opens one module')
 # Use hidden grid links only for disconnected components to keep pages compact.
 cols=2 if key in ['01_roles_payments','02_products_carts','03_orders_reviews'] else 3
 for i in range(len(types)):
  if i%cols<cols-1 and i+1<len(types):edges.add(f'{alias(types[i])} -[hidden]right-> {alias(types[i+1])}')
  if i+cols<len(types):edges.add(f'{alias(types[i])} -[hidden]down-> {alias(types[i+cols])}')
 lines+=sorted(edges)
 if key=='01_roles_payments':lines+=['note bottom of '+alias(top['PaymentMethod']),'CheckoutService holds PaymentMethod and calls pay(total).','COD returns PENDING; approved wallet returns PAID; declined wallet rejects checkout.','end note']
 if key=='02_products_carts':lines+=['note bottom of '+alias(top['PhotoFrame']),'Record components are private final fields.','Java generates public accessors mode(), x() and y().','end note']
 lines+=['@enduml'];block='\n'.join(lines)+'\n';blocks.append(block)
 (OUT/(key+'.puml')).write_text(block,encoding='utf-8')
 index.append({'id':key,'title':title,'classes':names})
assert set(used)==set(top),(set(top)-set(used),set(used)-set(top))
assert len(used)==len(set(used))
(ROOT/'docs/classes.puml').write_text('\n'.join(blocks),encoding='utf-8')
(OUT/'diagram-index.json').write_text(json.dumps(index,indent=2)+'\n',encoding='utf-8')
