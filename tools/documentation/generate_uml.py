ref=['# FORGE Java class reference','','Generated from Java compiler syntax trees. The source inventory records the exact file coverage and named types. It omits method bodies, field initializers and anonymous classes. Source links and source SHA-256 values are retained in source-inventory.json.','','`+` public, `#` protected, `-` private, `~` package access. Record components have private final storage and implicit public component accessors. Compiler-generated record equals/hashCode/toString and enum values/valueOf are not listed as explicitly declared methods. The readable UML sheets select operations; this reference preserves every declared member.','']
