T=json.loads((OUT/'source-inventory.json').read_text(encoding='utf-8'))
top={t['name']:t for t in T if not t['nested']}
for t in T:
 t['sourceSha256']=hashlib.sha256((ROOT/t['source']).read_bytes()).hexdigest()
(OUT/'source-inventory.json').write_text(json.dumps(T,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')

def alias(t):return re.sub('[^a-zA-Z0-9_]','_',t['qualifiedName'])
def visibility(m,kind=''):
 if 'private' in m:return '-'
 if 'protected' in m:return '#'
 if 'public' in m or kind=='INTERFACE':return '+'
 return '~'
def safe(s):return s.replace('"',"'").replace('{','(').replace('}',')').replace('\n',' ')
def declared(t,full=False):
 kind=t['kind'];prefix='interface' if kind=='INTERFACE' else 'enum' if kind=='ENUM' else 'abstract class' if 'abstract' in t['modifiers'] else 'class'
 stereo=' <<record>>' if kind=='RECORD' else ''
 lines=[f'{prefix} "{t["localName"]}" as {alias(t)}{stereo} {{']
 fields=t['fields']
 if not full and kind not in ['RECORD','ENUM'] and t['package'].endswith(('.service','.ui','.persistence')):
  fields=[f for f in fields if re.search(r'\b(?:Services|User|Cart|Product|DatabaseManager|\w+Service|\w+Repository|GeminiAssistant|ManagerAi|AiHttp|Clock|Memory|Profile)\b',f['type'])][:5]
 elif not full:fields=fields[:12]
 for f in fields:
  if f['enumConstant']:lines.append('  '+f['name']);continue
  flag='{static} ' if 'static' in f['modifiers'] else ''
  lines.append('  '+flag+visibility(f['modifiers'],kind)+safe(f['name'])+' : '+safe(f['type']))
 methods=t['methods']
 if not full:
  public=[m for m in methods if ('public' in m['modifiers'] or 'protected' in m['modifiers'] or kind=='INTERFACE')]
  public += [m for m in methods if 'private' not in m['modifiers'] and m not in public]
  unique={}
  for m in public:
   if m['name'] not in unique:unique[m['name']]=m
  # Reduce presentation helpers, but preserve distinct public contracts in the full member reference.
  preferred={'GeminiAssistant':['<init>','configurationProblem','answer','searchByImage','summarizeReviews','limitsSummary'],'ManagerAi':['<init>','classify','draft','configured','configurationProblem'],'ProductService':['<init>','search','get','save','delete','updateInventoryNumbers','applyManagerChanges'],'Cart':['<init>','getItems','add','setQuantity','remove','clear','getTotal','attachPersistence']}.get(t['name'],[])
  ordered=[unique[n] for n in preferred if n in unique]+[m for n,m in unique.items() if n not in preferred]
  methods=ordered[:(8 if t['package'].endswith(('.model','.payment')) or preferred else 6)]
 for m in methods:
  name=t['name'] if m['name']=='<init>' else m['name']
  params=', '.join(p['name']+(' : '+p['type'] if full else '') for p in m['parameters'])
  if not full and len(params)>62:params='...'
  flags=('{static} ' if 'static' in m['modifiers'] else '')+('{abstract} ' if 'abstract' in m['modifiers'] else '')
  lines.append('  '+flags+visibility(m['modifiers'],kind)+safe(name)+'('+safe(params)+')'+(' : '+safe(m['returnType']) if m['returnType'] else ''))
 if kind=='RECORD' and not full:lines.append('  .. public component accessors generated by Java ..')
 lines.append('}')
 return lines

